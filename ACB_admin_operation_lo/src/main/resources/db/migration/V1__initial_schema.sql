-- Cada route_id identifica una dirección (541 o 542) en el componente Routes.
CREATE TABLE trip (
    trip_id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_id                  BIGINT NOT NULL,
    route_code_snapshot       VARCHAR(4) NOT NULL,
    shift_code_snapshot       CHAR(3) NOT NULL,
    trip_date                 DATE NOT NULL,
    school_name_snapshot      VARCHAR(150) NOT NULL,
    scheduled_start_snapshot  TIME NOT NULL,
    actual_start_at           TIMESTAMPTZ,
    actual_end_at             TIMESTAMPTZ,
    start_point_id            BIGINT NOT NULL,
    start_point_code_snapshot VARCHAR(4) NOT NULL,
    completion_code           VARCHAR(3),

    CONSTRAINT uq_trip_route_date UNIQUE (route_id, trip_date),
    CONSTRAINT chk_trip_shift_code
        CHECK (shift_code_snapshot IN ('541', '542')),
    CONSTRAINT chk_trip_actual_times
        CHECK (
            actual_end_at IS NULL
            OR actual_start_at IS NULL
            OR actual_end_at >= actual_start_at
        ),
    CONSTRAINT fk_trip_completion_code
        FOREIGN KEY (completion_code) REFERENCES operation_code (code)
);

CREATE INDEX idx_trip_date ON trip (trip_date);


CREATE TABLE trip_student_attendance (
    trip_id                       BIGINT NOT NULL,
    student_id                    BIGINT NOT NULL,
    student_name_snapshot         VARCHAR(150) NOT NULL,
    status_code                   CHAR(2) NOT NULL,
    note                          TEXT,
    accompanying_person_name      VARCHAR(150),
    accompanying_person_relation  VARCHAR(100),
    recorded_by_user_id           BIGINT,
    recorded_at                   TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_trip_student_attendance PRIMARY KEY (trip_id, student_id),
    CONSTRAINT fk_attendance_trip
        FOREIGN KEY (trip_id) REFERENCES trip (trip_id) ON DELETE RESTRICT,
    CONSTRAINT chk_attendance_status
        CHECK (status_code IN ('00', '01', '0I', '0C'))
);

CREATE INDEX idx_attendance_student ON trip_student_attendance (student_id);


CREATE TABLE trip_guide_attendance (
    trip_guide_id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_id                      BIGINT NOT NULL,
    assignment_role              VARCHAR(10) NOT NULL,
    planned_guide_id             BIGINT NOT NULL,
    planned_guide_name_snapshot  VARCHAR(150) NOT NULL,
    actual_guide_id              BIGINT,
    actual_guide_name_snapshot   VARCHAR(150),
    arrived_at                   TIMESTAMPTZ,
    substitution_reason          TEXT,
    replacement_recorded_by_user_id BIGINT,
    replacement_recorded_at      TIMESTAMPTZ,

    CONSTRAINT uq_trip_guide_role UNIQUE (trip_id, assignment_role),
    CONSTRAINT fk_trip_guide_trip
        FOREIGN KEY (trip_id) REFERENCES trip (trip_id) ON DELETE RESTRICT,
    CONSTRAINT chk_trip_guide_role
        CHECK (assignment_role IN ('MAIN', 'SUPPORT'))
);

CREATE INDEX idx_trip_guide_planned_guide
    ON trip_guide_attendance (planned_guide_id);
CREATE INDEX idx_trip_guide_actual_guide
    ON trip_guide_attendance (actual_guide_id);


CREATE TABLE guide_check_in_attempt (
    check_in_attempt_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_guide_id        BIGINT NOT NULL,
    operation_code       VARCHAR(3) NOT NULL DEFAULT '523',
    attempted_at         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    latitude             NUMERIC(9, 6) NOT NULL,
    longitude            NUMERIC(10, 7) NOT NULL,
    distance_to_start_m  NUMERIC(10, 2),
    allowed_radius_m     NUMERIC(10, 2) NOT NULL,
    within_radius        BOOLEAN NOT NULL,
    within_time          BOOLEAN NOT NULL,
    accepted             BOOLEAN NOT NULL,
    rejection_reason     VARCHAR(200),
    source               VARCHAR(30) NOT NULL DEFAULT 'OPERATION',
    source_event_id      VARCHAR(150),

    CONSTRAINT fk_check_in_trip_guide
        FOREIGN KEY (trip_guide_id)
        REFERENCES trip_guide_attendance (trip_guide_id) ON DELETE RESTRICT,
    CONSTRAINT fk_check_in_operation_code
        FOREIGN KEY (operation_code) REFERENCES operation_code (code),
    CONSTRAINT chk_check_in_code CHECK (operation_code = '523'),
    CONSTRAINT chk_check_in_latitude CHECK (latitude BETWEEN -90 AND 90),
    CONSTRAINT chk_check_in_longitude CHECK (longitude BETWEEN -180 AND 180),
    CONSTRAINT chk_check_in_distance
        CHECK (distance_to_start_m IS NULL OR distance_to_start_m >= 0),
    CONSTRAINT chk_check_in_radius CHECK (allowed_radius_m >= 0),
    CONSTRAINT chk_check_in_rejection_reason
        CHECK (accepted OR rejection_reason IS NOT NULL),
    CONSTRAINT uq_check_in_source_event UNIQUE (source, source_event_id)
);

CREATE INDEX idx_check_in_trip_guide_time
    ON guide_check_in_attempt (trip_guide_id, attempted_at DESC);


CREATE TABLE trip_event (
    trip_event_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_id             BIGINT NOT NULL,
    operation_code      VARCHAR(3) NOT NULL,
    occurred_at         TIMESTAMPTZ NOT NULL,
    description         TEXT,
    latitude            NUMERIC(9, 6),
    longitude           NUMERIC(10, 7),
    source              VARCHAR(30) NOT NULL,
    source_event_id     VARCHAR(150),
    reported_by_user_id BIGINT,
    reporter_type       VARCHAR(10) NOT NULL,
    recorded_at         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_trip_event_trip
        FOREIGN KEY (trip_id) REFERENCES trip (trip_id) ON DELETE RESTRICT,
    CONSTRAINT fk_trip_event_operation_code
        FOREIGN KEY (operation_code) REFERENCES operation_code (code),
    CONSTRAINT chk_trip_event_reporter_type
        CHECK (reporter_type IN ('GUIDE', 'ADMIN', 'SYSTEM')),
    CONSTRAINT chk_trip_event_latitude
        CHECK (latitude IS NULL OR latitude BETWEEN -90 AND 90),
    CONSTRAINT chk_trip_event_longitude
        CHECK (longitude IS NULL OR longitude BETWEEN -180 AND 180),
    CONSTRAINT uq_trip_event_source_event UNIQUE (source, source_event_id)
);

CREATE INDEX idx_trip_event_trip_time
    ON trip_event (trip_id, occurred_at);


CREATE TABLE guide_fault_cycle (
    cycle_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    guide_id   BIGINT NOT NULL,
    status     VARCHAR(12) NOT NULL DEFAULT 'OPEN',
    opened_at  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    closed_at  TIMESTAMPTZ,

    CONSTRAINT chk_guide_fault_cycle_status
        CHECK (status IN ('OPEN', 'CONVERTED')),
    CONSTRAINT chk_guide_fault_cycle_dates
        CHECK (
            (status = 'OPEN' AND closed_at IS NULL)
            OR (status = 'CONVERTED' AND closed_at IS NOT NULL)
        )
);

CREATE UNIQUE INDEX uq_one_open_fault_cycle_per_guide
    ON guide_fault_cycle (guide_id)
    WHERE status = 'OPEN';


CREATE TABLE minor_fault (
    minor_fault_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cycle_id            BIGINT NOT NULL,
    trip_guide_id       BIGINT NOT NULL,
    sequence_in_cycle   SMALLINT NOT NULL,
    reason              VARCHAR(200) NOT NULL,
    status              VARCHAR(10) NOT NULL DEFAULT 'PENDING',
    notification_type   VARCHAR(20) NOT NULL,
    managed_by_user_id  BIGINT,
    recorded_at         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    notified_at         TIMESTAMPTZ,

    CONSTRAINT uq_minor_fault_cycle_sequence
        UNIQUE (cycle_id, sequence_in_cycle),
    CONSTRAINT fk_minor_fault_cycle
        FOREIGN KEY (cycle_id) REFERENCES guide_fault_cycle (cycle_id)
        ON DELETE RESTRICT,
    CONSTRAINT fk_minor_fault_trip_guide
        FOREIGN KEY (trip_guide_id)
        REFERENCES trip_guide_attendance (trip_guide_id) ON DELETE RESTRICT,
    CONSTRAINT chk_minor_fault_sequence
        CHECK (sequence_in_cycle BETWEEN 1 AND 5),
    CONSTRAINT chk_minor_fault_status
        CHECK (status IN ('PENDING', 'NOTIFIED')),
    CONSTRAINT chk_minor_fault_notification_type
        CHECK (notification_type IN ('VERBAL', 'EMAIL', 'REQUIREMENT')),
    CONSTRAINT chk_minor_fault_notification_sequence
        CHECK (
            (sequence_in_cycle IN (1, 2) AND notification_type = 'VERBAL')
            OR (sequence_in_cycle IN (3, 4) AND notification_type = 'EMAIL')
            OR (sequence_in_cycle = 5 AND notification_type = 'REQUIREMENT')
        ),
    CONSTRAINT chk_minor_fault_notification_dates
        CHECK (
            (status = 'PENDING' AND notified_at IS NULL)
            OR (status = 'NOTIFIED' AND notified_at IS NOT NULL)
        )
);

CREATE INDEX idx_minor_fault_cycle ON minor_fault (cycle_id);


CREATE TABLE major_fault (
    major_fault_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_guide_id       BIGINT NOT NULL,
    cycle_id            BIGINT UNIQUE,
    origin              VARCHAR(20) NOT NULL,
    status              VARCHAR(10) NOT NULL DEFAULT 'OPEN',
    managed_by_user_id  BIGINT,
    opened_at           TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    notified_at         TIMESTAMPTZ,
    closed_at           TIMESTAMPTZ,

    CONSTRAINT fk_major_fault_trip_guide
        FOREIGN KEY (trip_guide_id)
        REFERENCES trip_guide_attendance (trip_guide_id) ON DELETE RESTRICT,
    CONSTRAINT fk_major_fault_cycle
        FOREIGN KEY (cycle_id) REFERENCES guide_fault_cycle (cycle_id)
        ON DELETE RESTRICT,
    CONSTRAINT chk_major_fault_origin
        CHECK (
            (origin = 'DIRECT' AND cycle_id IS NULL)
            OR (origin = 'FIVE_MINORS' AND cycle_id IS NOT NULL)
        ),
    CONSTRAINT chk_major_fault_status
        CHECK (status IN ('OPEN', 'NOTIFIED', 'MINUTED')),
    CONSTRAINT chk_major_fault_dates
        CHECK (
            (status = 'OPEN' AND notified_at IS NULL AND closed_at IS NULL)
            OR (status = 'NOTIFIED' AND notified_at IS NOT NULL AND closed_at IS NULL)
            OR (status = 'MINUTED' AND notified_at IS NOT NULL AND closed_at IS NOT NULL)
        )
);
