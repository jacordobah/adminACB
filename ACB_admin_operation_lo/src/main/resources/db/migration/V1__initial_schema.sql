-- Los IDs de rutas, puntos, estudiantes y usuarios son referencias externas;
-- no se crean claves foráneas hacia las bases de datos de otros componentes.

CREATE TABLE operation_code (
    code        VARCHAR(3) PRIMARY KEY,
    description VARCHAR(200) NOT NULL,
    active      BOOLEAN NOT NULL DEFAULT TRUE
);

